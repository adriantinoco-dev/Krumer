  init() {
    const saved = localStorage.getItem('krumer_language') || 'pt-br';
    this._current = saved;
    this.apply();
  },

  t(key, ...args) {
    const lang = this._translations[this._current] || this._translations['pt-br'];
    let text = (lang && lang[key]) || (this._translations['pt-br'] ? this._translations['pt-br'][key] : undefined) || key;
    args.forEach((arg, i) => {
      text = text.replace(`{${i}}`, arg);
    });
    return text;
  },

  getLang() {
    return this._current;
  },

  setLang(lang) {
    this._current = lang || 'pt-br';
    this.apply();
  },

  apply() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.dataset.i18n;
      const text = this.t(key);
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = text;
      } else {
        el.textContent = text;
      }
    });

    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.dataset.i18nHtml;
      if (key === 'settings.api_key_help') {
        const link = '<a href="https://aistudio.google.com/app/apikey" target="_blank" rel="noopener noreferrer">Google AI Studio</a>';
        el.innerHTML = this.t(key, link);
      } else {
        el.innerHTML = this.t(key);
      }
    });

    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      el.title = this.t(el.dataset.i18nTitle);
    });

    document.querySelectorAll('[data-i18n-alt]').forEach(el => {
      el.alt = this.t(el.dataset.i18nAlt);
    });

    document.documentElement.lang = this._current.replace('_', '-');

    if (window.app) {
      if (window.app.libraryManager) {
        window.app.libraryManager.renderGrid();
        window.app.libraryManager.loadTags();
        window.app.libraryManager._renderListsInSidebar();
        if (window.app.libraryManager.selectedItem && document.getElementById('book-details-view')?.style.display !== 'none') {
          window.app.libraryManager.openBookDetails(window.app.libraryManager.selectedItem.id);
        }
        window.app.libraryManager._ensureContextMenu();
      }
      if (typeof window.app._renderApiKeyStatus === 'function') {
        window.app._renderApiKeyStatus();
      }
      if (typeof window.app.renderShortcuts === 'function') {
        const atalhosPanel = document.querySelector('.settings-panel[data-panel="atalhos"]');
        if (atalhosPanel && atalhosPanel.classList.contains('active')) {
          window.app.renderShortcuts();
        }
      }
    }
  },
